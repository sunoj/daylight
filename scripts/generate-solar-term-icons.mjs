const command = {M: ['move',2], L:['line',2], C:['curve',6], Z:['close',0]};
function swiftPath(shape) {
  const tokens = shape.d.match(/[MLCZ]|-?\d*\.?\d+/g);
  const lines = ['        let path = NSBezierPath()'];
  const pt = (x,y) => `CGPoint(x: ${x}, y: ${rounded(24-y)})`;
  while(tokens.length) {
    const op = tokens.shift();
    if (!command[op]) throw Error(`Unsupported command ${op}`);
    const v = tokens.splice(0,command[op][1]).map(Number);
    if (op === 'Z') lines.push('        path.close()');
    else if(op === 'C') lines.push(`        path.curve(to: ${pt(v[4],v[5])}, controlPoint1: ${pt(v[0],v[1])}, controlPoint2: ${pt(v[2],v[3])})`);
    else lines.push(`        path.${command[op][0]}(to: ${pt(v[0],v[1])})`);
  }
  lines.push(`        return SolarTermIconShape(path: path, mode: .${shape.mode}, lineWidth: ${shape.width}, opacity: ${shape.opacity}, tone: .${shape.tone})`);
  return lines.join('\n');
}
